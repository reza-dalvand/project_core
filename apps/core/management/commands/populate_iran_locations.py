    def add_color(self, text, color_code):
        """Add ANSI color to text"""
        return f"\033[{color_code}m{text}\033[0m"

    @transaction.atomic
    def handle(self, *args, **options):
        self.stdout.write(self.add_color('🌍 Starting to populate Iran provinces and cities...', '1;36'))

        provinces_created = 0
        provinces_updated = 0
        cities_created = 0
        cities_updated = 0

        for province_name, city_list in self.iran_locations.items():
            # Create or get province
            province, created = Province.objects.get_or_create(
                name=province_name,
                defaults={'is_active': True}
            )

            if created:
                provinces_created += 1
                self.stdout.write(f'✅ Province created: {self.add_color(province_name, "1;33")}')
            else:
                provinces_updated += 1
                self.stdout.write(f'ℹ️  Province exists: {self.add_color(province_name, "0;33")}')

            # Create or get cities for this province
            for city_name in city_list:
                city, city_created = City.objects.get_or_create(
                    name=city_name,
                    province=province,
                    defaults={'is_active': True}
                )

                if city_created:
                    cities_created += 1
                else:
                    cities_updated += 1

        total_provinces = Province.objects.count()
        total_cities = City.objects.count()

        self.stdout.write('\n' + '='*50)
        self.stdout.write(self.add_color('📊 Summary:', '1;32'))
        self.stdout.write(f'   New provinces created: {provinces_created}')
        self.stdout.write(f'   Existing provinces: {provinces_updated}')
        self.stdout.write(f'   New cities created: {cities_created}')
        self.stdout.write(f'   Existing cities: {cities_updated}')
        self.stdout.write(f'   Total provinces in DB: {total_provinces}')
        self.stdout.write(f'   Total cities in DB: {total_cities}')
        self.stdout.write('='*50)
        self.stdout.write(self.add_color('✅ Done! All Iran provinces and cities have been populated.', '1;32'))
